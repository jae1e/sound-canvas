/**
 * Downloadable model sets. URLs and checksums are plain constants so they can be changed
 * (mirror, different model) without touching the downloader. Models are never bundled in the APK.
 *
 * Sources (checked 2026-11-03):
 *  - Korean: huggingface.co/kangkyu/icefall-asr-ko-streaming-zipformer-174m (Apache-2.0, KsponSpeech-trained,
 *    int8 streaming zipformer, chunk-16 / left-128 variant = lowest latency).
 *  - English: huggingface.co/csukuangfj/sherpa-onnx-streaming-zipformer-en-2023-06-26 (Apache-2.0).
 *  - Silero VAD: k2-fsa/sherpa-onnx "asr-models" release asset.
 * SHA-256 values are the Hugging Face LFS object ids (== SHA-256 of the file) or computed by us.
 *
 * Licenses (commercial use must be allowed for every model; recorded 2026-11-03, verify before shipping):
 *  - Silero VAD: MIT (https://github.com/snakers4/silero-vad/blob/master/LICENSE). Commercial use OK.
 *  - Korean zipformer ASR: Apache-2.0 per model card. DOUBT: trained on KsponSpeech + "AIHub mix" (about 6,500 h);
 *    the AI Hub / KsponSpeech data terms are separate from the weights' license (AI Hub data is distributed under
 *    its own use terms, historically restricted to Korean entities). Needs legal review before commercial release.
 *  - English zipformer ASR: Apache-2.0 per model card (LibriSpeech-trained, LibriSpeech is CC BY 4.0). Commercial OK.
 *  - Supertonic 3 TTS (Supertone, https://huggingface.co/Supertone/supertonic-3): weights are OpenRAIL-M (NOT OSI open
 *    source): commercial use allowed but with use-based restrictions (License Attachment A) that must be passed to
 *    downstream users, and the licensor reserves a right to restrict usage in violation. Sample code MIT. Upstream
 *    repo is archived. The sherpa-onnx int8 package carries the same weights.
 *  - Kokoro-82M v1.0 TTS (https://huggingface.co/hexgrad/Kokoro-82M): Apache-2.0 weights. DOUBTS: training data
 *    includes "synthetic audio generated by closed TTS models from large providers" (their output terms are not
 *    documented there), and CC BY audio (Koniwa tnc CC BY 3.0, SIWIS CC BY 4.0) which needs attribution. The
 *    sherpa-onnx package bundles espeak-ng-data (GPL-3.0 data/library: espeak-ng is linked into the sherpa-onnx native
 *    lib for phonemization) - a distribution/licensing question for a closed-source commercial app. Review before release.
 *  - ML Kit GenAI TTS: not a model we ship; Google's SDK + Google Speech Services voices under Google terms (alpha).
 */
/**
 * @param archive true when the file is a tar.bz2 that must be extracted into the set directory (top-level folder
 *   stripped) after download + checksum verification; the archive is then deleted and replaced by a marker file.
 * @param extractSkip entry paths (relative to the archive's top folder) starting with any of these are not extracted.
 */
data class ModelFile(
  val name: String,
  val url: String,
  val sizeBytes: Long,
  val sha256: String,
  val archive: Boolean = false,
  val extractSkip: List<String> = emptyList(),
)

data class ModelSet(val id: String, val title: String, val files: List<ModelFile>) {
  val totalBytes: Long get() = files.sumOf { it.sizeBytes }
}

